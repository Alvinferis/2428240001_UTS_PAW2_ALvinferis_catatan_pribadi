import mongoose from 'mongoose'

const catatanSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: true,
      trim: true,
    },
    content: {
      type: String,
      required: true,
      trim: true,
    },
    category: {
      type: String,
      required: true,
      trim: true,
    },
  },
  {
    timestamps: true,
  },
)

const CatatanModel = mongoose.model('catatan', catatanSchema)

export default CatatanModel